"""
recognize.py

本脚本用于通过 Google Gemini 大模型的深度多模态感知能力，对给定的合成/真实音频文件进行逆向声纹分析，
自动提取音色、发声习惯、情感底色以及双人交互节奏等高维语音特征，并将其输出为可以直接指导下一代
语音生成模型 (如 Gemini TTS 等) 的标准 Prompt 文件。

Date: 2026-05
"""

import os
from google import genai

# ==========================================
# 1. 初始化环境变量与 Gemini 客户端
# ==========================================
# 生产环境下推荐通过环境变量注入 GEMINI_API_KEY
os.environ['GEMINI_API_KEY'] = ''
client = genai.Client()

# ==========================================
# 2. 本地音频媒体上传
# ==========================================
# 指定待进行逆向分析的目标音频文件。
# 该文件将被暂存至 Google 云端工作区进行多模态分析。
audio_path = "story.wav"
print(f"正在上传音频文件: {audio_path} ...")
audio_file = client.files.upload(file=audio_path)
print("上传成功！")

# ==========================================
# 3. 构建逆向工程分析的系统提示词 (System Prompt)
# ==========================================
# 这里定义了极为细致的 Few-Shot / Zero-Shot 角色工程提示词。
# 将大模型扮演为一个专业的“配音导演”和“AI语音算法工程师”，强制要求其以客观、指令化的口吻输出，
# 以避免生成无用的对话寒暄（降低大模型的冗余回复，确保结构化输出）。
prompt = """
你现在是一位顶级的配音导演与 AI 语音算法工程师。请仔细聆听这段音频，对其中的人声特征进行“极致的逆向工程”。

【绝对核心规则】
你的「全部输出」将被我直接复制，并作为提示词（Prompt）原封不动地输入给下一个语音生成大模型。因此，绝对不要包含任何对话式的废话、寒暄语或报告框架（例如：禁止输出“好的，为您生成提示词”、“以下是分析结果”、“请看以下内容”）。
你的第一个字必须直接是指导声音生成的指令文本，并且全文都要保持这种“精准描绘、下达指令”的语境。

请按照以下结构，穷尽你能听到的所有细节，撰写这份「极端详尽的语音生成提示词」：

【全局声场与氛围设定】
请用描述性指令设定整体的录音基调、对话氛围、空间感，以及两个角色之间的互动节奏感。

【角色 1：发音人声纹与演绎指南】
- 物理声纹建模：详细设定发音人的性别、精确的感知年龄段、音高基准、共鸣位置（如胸腔共鸣、鼻腔共鸣等）、音色质感（如磁性、颗粒感、清脆、沙哑、气声比例、润泽度、厚度等）。
- 情绪底色与语气倾向：详细设定该角色核心的性格色彩和情绪基调，以及说话时带有的微表情（如眼带笑意、眉头紧锁、天真烂漫等引发的声带变化）。
- 咬字、韵律与发声习惯：设定语速的基准与动态变化区间、咬字清晰度（字正腔圆还是带有随性的连读/吞音）、特定的发音习惯（如特定的唇齿音、呼吸声、句末叹息）、句首和句末的语调走向（上扬/下沉/平拖），以及长句中的呼吸与停顿节奏。

【角色 2：发音人声纹与演绎指南】
（请完全按照角色 1 的极致细节维度，对第二位发音人进行全面、精确的指令设定。）

【场景交互与动态变化微调】
指导大模型在生成这两人对话时，应如何处理对话的交替：例如响应的快慢、情绪的递进或起伏、特定词语的重音强调等细节。

请直接开始输出这份提示词。
"""

# ==========================================
# 4. 调用大模型进行多模态音频分析
# ==========================================
print("Gemini 正在深度分析音频特征，请稍候...")
response = client.models.generate_content(
    # 推荐使用 1.5 Pro 或更高版本的 Pro 模型进行深度推理与长文本生成
    model="gemini-3.1-pro-preview", 
    contents=[audio_file, prompt]
)

# ==========================================
# 5. 落盘保存分析结果
# ==========================================
# 将分析所得的定制化生成 Prompt 保存至本地文件，
# 该文件可被后续流水线直接加载复用以克隆相似声音特征。
print("\n======= 🎵 Gemini 音频逆向分析结束 =======")
with open("prompt_2.txt", "w", encoding="utf-8") as f:
    f.write(response.text)
print("分析报告已成功导出为 prompt_2.txt。")